'use strict';

// Writes build/icon.svg: the Rorschach mark, a mirrored "R" torn into an ink blot.
// The letter is converted from the Anton typeface to a path so the SVG depends on
// no installed font. Usage: node scripts/icon-svg.js [path/to/Anton-Regular.ttf]
// Without an argument the font is fetched from the google/fonts repository (OFL)
// into build/fonts/, which is ignored by git.

const fs = require('node:fs');
const path = require('node:path');
const opentype = require('opentype.js');

const FONT_URL = 'https://github.com/google/fonts/raw/main/ofl/anton/Anton-Regular.ttf';
const OUT = path.join(__dirname, '..', 'build', 'icon.svg');

// The mark, as settled on the options page. Half of the card is drawn, filtered,
// and mirrored with <use>, so both sides tear identically.
const MARK = {
  size: 352,          // font size in a 512 box
  baseline: 418,
  foldOverlap: 10,    // how far the R's advance runs past the fold at x = 256
  seed: 2,
  detail: 0.017,      // noise frequency
  roughness: 4,       // displacement, px
  bleed: 2.2,         // blur before the threshold
  radius: 112,        // card corner radius
  card: '#f6f5f0',
  ink: '#15181d',
};

async function fontFile(arg) {
  if (arg) return path.resolve(arg);
  const dir = path.join(__dirname, '..', 'build', 'fonts');
  const file = path.join(dir, 'Anton-Regular.ttf');
  if (!fs.existsSync(file)) {
    fs.mkdirSync(dir, { recursive: true });
    const res = await fetch(FONT_URL);
    if (!res.ok) throw new Error(`Could not fetch ${FONT_URL}: ${res.status}`);
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  return file;
}

function glyphPath(file, m) {
  const buf = fs.readFileSync(file);
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const advance = font.getAdvanceWidth('R', m.size);
  const x = 256 + m.foldOverlap - advance;     // text-anchor="end" at the fold
  return font.getPath('R', x, m.baseline, m.size).toPathData(1);
}

function svg(d, m) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="Rorschach">
  <!-- Generated by scripts/icon-svg.js; the letter is Anton (OFL) as a path. -->
  <defs>
    <filter id="blot" x="-25%" y="-25%" width="150%" height="150%" color-interpolation-filters="sRGB">
      <feTurbulence type="fractalNoise" baseFrequency="${m.detail}" numOctaves="3" seed="${m.seed}" result="noise"/>
      <feDisplacementMap in="SourceGraphic" in2="noise" scale="${m.roughness}" xChannelSelector="R" yChannelSelector="G" result="torn"/>
      <feGaussianBlur in="torn" stdDeviation="${m.bleed}" result="soft"/>
      <feComponentTransfer in="soft"><feFuncA type="linear" slope="22" intercept="-8"/></feComponentTransfer>
    </filter>
  </defs>
  <rect width="512" height="512" rx="${m.radius}" fill="${m.card}"/>
  <g fill="${m.ink}">
    <g id="half" filter="url(#blot)">
      <path d="${d}"/>
      <circle cx="252" cy="104" r="15"/>
      <circle cx="243" cy="78" r="7"/>
      <circle cx="256" cy="448" r="12"/>
      <circle cx="247" cy="486" r="5"/>
      <ellipse cx="168" cy="455" rx="9" ry="6"/>
      <circle cx="122" cy="118" r="4"/>
    </g>
    <use href="#half" transform="translate(512 0) scale(-1 1)"/>
  </g>
</svg>
`;
}

(async () => {
  const file = await fontFile(process.argv[2]);
  const d = glyphPath(file, MARK);
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, svg(d, MARK));
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${d.length} chars of path data from ${path.basename(file)})`);
})().catch((e) => { console.error(e.message); process.exit(1); });
